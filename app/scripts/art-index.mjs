// Writes src/data/art-index.ts: a static require() for each piece of art the screens use, because
// React Native only bundles images named by a literal path. The art kit stays the one source (rule 5):
// run `npm run art-index` after the art changes. It holds the app sprites (assets/app/sprites, made by
// tools/asset_generation/app_sprites.py, D-111: the plants, the jar, the Home extras and the badges,
// pre-enlarged nearest-neighbour), every isometric kit piece in its three times of day with its geometry (the Home
// scene, D-113), and the kit's times of day.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, "..", "..", "assets");
const out = join(here, "..", "src", "data", "art-index.ts");

const manifest = JSON.parse(readFileSync(join(assets, "isometric", "manifest.json"), "utf-8"));
const sheet = JSON.parse(readFileSync(join(assets, "app", "sprites", "sprites.json"), "utf-8"));
const atlas = JSON.parse(readFileSync(join(assets, "app", "atlas", "atlas.json"), "utf-8"));
const names = Object.keys(sheet.sprites).sort();
const times = Object.keys(manifest.times);

const lines = [
  "// Generated by scripts/art-index.mjs from assets/isometric/manifest.json and",
  "// assets/app/sprites/sprites.json. Don't edit by hand.",
  "import type { Period } from '@/lib/timeOfDay';",
  "",
  `export const TIMES: Record<Period, string> = ${JSON.stringify(manifest.times)};`,
  "",
  "export const SPRITES: Record<string, Record<Period, number>> = {",
  ...names.map((n) => `  ${n}: { ${times.map((t) =>
    `${t}: require('../../../assets/app/sprites/${sheet.sprites[n].files[t]}')`).join(", ")} },`),
  "};",
  "",
  "/** Each sprite's size in image pixels, [width, height]. */",
  "export const SPRITE_SIZE: Record<string, [number, number]> = {",
  ...names.map((n) => `  ${n}: [${sheet.sprites[n].size[0]}, ${sheet.sprites[n].size[1]}],`),
  "};",
  "",
  "/** The isometric kit packed into one atlas page per time of day (assets/app/atlas, D-114). */",
  `export const ATLAS: Record<Period, number> = { ${times.map((t) =>
    `${t}: require('../../../assets/app/atlas/${atlas.files[t]}')`).join(", ")} };`,
  "",
  "/** Each kit piece in the atlas: [x, y, w, h] on the page, drawn at (ox, oy) on its canvas. */",
  "export const KIT_RECT: Record<string, [number, number, number, number, number, number]> = {",
  ...manifest.pieces.map((p) => `  ${p.name}: [${atlas.pieces[p.name].join(", ")}],`),
  "};",
  "",
  "/** Each kit piece's [footprint x, footprint y, canvas width, canvas height, cells along gx, along gy]. */",
  "export const KIT_GEOM: Record<string, [number, number, number, number, number, number]> = {",
  ...manifest.pieces.map((p) => `  ${p.name}: [${[...p.footprint_origin, ...p.canvas, ...p.cells].join(", ")}],`),
  "};",
  "",
  "/** Each kit piece's opaque box on its canvas, [x0, y0, x1, y1), from the atlas: taps (D-114). */",
  "export const KIT_BOX: Record<string, [number, number, number, number]> = {",
  ...manifest.pieces.map((p) => {
    const [, , w, h, ox, oy] = atlas.pieces[p.name];
    return `  ${p.name}: [${[ox, oy, ox + w, oy + h].join(", ")}],`;
  }),
  "};",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`${names.length} sprites, ${manifest.pieces.length} kit pieces in ${times.length} atlas pages -> src/data/art-index.ts`);
