def build_character() -> dict:
    """D-125: the kit's own recolouring (palette.to_rgba with a skin tone) and its glasses rule
    (characters.json: over a front frame whose 'glasses' is true, moved up by its head_dy), for a few
    frames; app/src/lib/__tests__/character.test.ts paints them from the atlas's pixels and must match."""
    import base64

    import numpy as np

    from tools.asset_generation import palette as P
    from tools.asset_generation.kit import PIECES
    chars = json.loads((ROOT / "assets" / "isometric" / "characters.json").read_text(encoding="utf-8"))
    by = {p.name: p for p in PIECES}
    b64 = lambda a: base64.b64encode(np.ascontiguousarray(a, dtype=np.uint8).tobytes()).decode()   # noqa: E731

    def box(a):
        ys, xs = np.nonzero(a >= 0)
        return [int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1]
    glasses = by["glasses_front"].render()
    gb = box(glasses)
    cases = []
    for avatar, tone, wear, t, frame in CHARACTER_CASES:
        info = chars["avatars"][avatar - 1]["frames"][frame]
        art = by[f"avatar_0{avatar}_{frame}"].render()
        fb = box(art)
        comp, union = art.copy(), list(fb)
        if wear and info["glasses"]:
            dy = info["head_dy"]
            shifted = np.full_like(glasses, P.TRANSPARENT)
            shifted[:glasses.shape[0] - dy] = glasses[dy:]             # up by head_dy
            comp = np.where(shifted >= 0, shifted, comp)
            union = [min(fb[0], gb[0]), min(fb[1], gb[1] - dy), max(fb[2], gb[2]), max(fb[3], gb[3] - dy)]
        crop = lambda a, b: a[b[1]:b[3], b[0]:b[2]]                     # noqa: E731
        cases.append({
            "avatar": avatar, "tone": tone, "glasses": wear, "period": t, "frame": frame, "head_dy": info["head_dy"],
            "frame_glasses": info["glasses"], "frame_box": fb, "glasses_box": gb, "union": union,
            "frame_rgba": b64(crop(P.to_rgba(art, t), fb)), "glasses_rgba": b64(crop(P.to_rgba(glasses, t), gb)),
            "expected": b64(crop(P.to_rgba(comp, t, tone - 1), union)),
        })
    return {"note": "Generated by tools/app_fixtures.py from the kit (palette.to_rgba); do not edit by hand.", "cases": cases}


