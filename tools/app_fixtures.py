def day(p: dict, today: date) -> dict:
    """What one persona's screens read on one study date: GET /v1/assess, /v1/game, /v1/future and
    /v1/card exactly as api/main.py builds them (no Supabase: the persona's rows come from personas.json),
    and the check-ins the app reads from Supabase itself (D-118)."""
    from api import cards
    from tools.personas.build import game_facts
    money = m.as_of(m.MoneyFacts(profile=p["profile"], transactions=p["transactions"], debts=p["debts"],
                                 checkins=p["checkins"]), today)
    profile, records, months = m.assess_inputs(money, today)
    upto = m.assessed_upto(months)
    result = assess(profile, records[:upto])
    prof, inputs = g.game_inputs(game_facts(p, today))
    st = replay(prof, today, strict=False, **inputs)
    from api import assistant
    week = cards.monday(today).isoformat()                        # the persona's own answer that week (D-119)
    answer = next(({"event_id": c["event_id"], "response": c["response"]} for c in p["cards"] if c["week"] == week), None)
    return {
        "card": cards.card_view(p["profile"], p["key"], today, st.money, answer),
        "checkins": [c for c in p["checkins"] if c["month"] < today.replace(day=1).isoformat()],   # rows RLS shows by then
        "assess": {**result, "as_of": today.isoformat(), "assessed_month": months[upto - 1]["month"], "months": months},
        "game": g.game_view(st, today, set()),
        "future": {**m.future_view(p["profile"], records, months, st, prof, p["key"], today), "as_of": today.isoformat()},
        # what POST /v1/assistant would give Groq that day (D-123): sample data can't reach the AI, so the
        # money helper screen shows this instead, labelled as what the AI would see
        "helper_facts": assistant.build_context(result, p["profile"]["employment_type"], months[upto - 1]["month"]),
    }


