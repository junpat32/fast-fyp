def scene_draws(scene: dict, origins: dict) -> dict:
    """What preview.phone_scene draws, as lists of [piece, x, y] (x, y: the image's top-left in the
    540 x 1200 view; a "|flip" piece is mirrored, so its origin moves to w - x - 64)."""
    from tools.asset_generation.preview import PHONE, ROOM_TOP
    W, H = PHONE
    ox, oy = ROOM_TOP[0] - 32, ROOM_TOP[1]

    def at(gx, gy, name):
        base, _, flip = name.partition("|")
        (fx, fy), (w, _) = origins[base]
        if flip:
            fx = w - fx - 64
        return [name, ox + (gx - gy) * 32 - fx, oy + (gx + gy) * 16 - fy]
    s_range = range(math.floor((-oy - 32) / 16), math.ceil((H - oy) / 16) + 1)
    t_range = range(math.floor((-ox - 64) / 32), math.ceil((W - ox) / 32) + 1)
    cells = [((s + t) // 2, (s - t) // 2) for s in s_range for t in t_range if (s + t) % 2 == 0]
    return {"ground": [at(gx, gy, scene["ground"].get((gx, gy), scene["default"])) for gx, gy in cells],
            "decals": [at(gx, gy, n) for (gx, gy), n in scene.get("decals", [])],
            "background": [at(gx, gy, n) for (gx, gy), n in scene["background"]],
            "structs": [at(gx, gy, n) for (gx, gy), n in scene["structs"]]}


