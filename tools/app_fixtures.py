def sizes() -> dict[str, tuple[int, int]]:
    return {p["name"]: tuple(p["cells"]) for p in json.loads(MANIFEST.read_text(encoding="utf-8"))["pieces"]}


def build() -> dict:
    size = sizes()
    size_of = lambda item: size.get(item[1].partition("|")[0], (1, 1))   # noqa: E731
    out = {"note": "Generated by tools/app_fixtures.py from scenes.depth_sort; do not edit by hand.", "cases": []}
    for name, kw in CASES.items():
        structs = scenes.home_scene(**kw)["structs"]
        # front cell only, ties in reverse: the order that drew the sofa over the coffee table (D-88),
        # so depth_sort has real work to do (an easy order would leave the fixture nothing to check)
        incoming = sorted(reversed(structs), key=lambda s: s[0][0] + s[0][1] + sum(size_of(s)) - 2)
        expected = scenes.depth_sort(incoming, size_of)
        index = {id(s): i for i, s in enumerate(incoming)}
        out["cases"].append({
            "name": name,
            "items": [{"gx": c[0], "gy": c[1], "w": size_of((c, n))[0], "d": size_of((c, n))[1], "name": n}
                      for c, n in incoming],
            "expected": [index[id(s)] for s in expected],
        })
    return out


def write() -> str:
    text = json.dumps(build(), indent=1) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    return text


