def build_samples() -> dict[str, dict]:
    return {p["key"]: _plain(sample(p)) for p in _personas()}


def build_travel() -> dict[str, dict]:
    return {p["key"]: _plain(travel(p)) for p in _personas()}


def write_samples() -> dict[str, dict]:
    data = build_samples()
    SAMPLES.mkdir(parents=True, exist_ok=True)
    for key, s in data.items():
        (SAMPLES / f"{key}.json").write_text(json.dumps(s, indent=1) + "\n", encoding="utf-8")
    TRAVEL.mkdir(parents=True, exist_ok=True)
    for key, t in build_travel().items():                        # compact: six dates each, bundled into the app
        (TRAVEL / f"{key}.json").write_text(json.dumps(t, separators=(",", ":")) + "\n", encoding="utf-8")
    return data


