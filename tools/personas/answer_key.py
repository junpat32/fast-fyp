"""Answer keys for the study's comprehension questions (T-18; docs/ethics/04_questionnaire.md Part B).

    .venv\\Scripts\\python -m tools.personas.answer_key       # -> docs/study/answer_keys.md

The questions were fixed before the personas existed; the keys come from what the app shows each
persona on its start date (1 July 2026: each participant's fresh persona copies start there, D-94,
and Part B is answered before time travel, D-95), computed with the API's own functions
(api.money, engine.assess), so a key can never disagree with the screen. An answer within 2 percentage points (or 0.05 months) of a bucket's edge
is flagged, because the rounded number on screen could be read either way.
"""
from __future__ import annotations

import json
from datetime import date

from api import money as m
from engine.assess import assess

from .build import OUT, ROOT, STUDY_FIRST

DOC = ROOT / "docs" / "study" / "answer_keys.md"
BAND_WORDS = {"GREEN": "Green", "YELLOW": "Yellow", "RED": "Red", "INSUFFICIENT_INCOME": '"Not enough income data"'}


def dsr_bucket(dsr: float) -> tuple[str, bool]:
    edges = [(0.30, "under 30%"), (0.60, "30% to under 60%")]
    for edge, label in edges:
        if dsr < edge:
            return label, abs(dsr - edge) < 0.02 or (edge == 0.60 and abs(dsr - 0.30) < 0.02)
    return "60% or more", abs(dsr - 0.60) < 0.02


def cushion_bucket(months: float) -> tuple[str, bool]:
    if months < 1:
        return "less than 1", abs(months - 1) < 0.05
    if months < 3:
        return "1–2", abs(months - 1) < 0.05 or abs(months - 3) < 0.05
    return "3 or more", abs(months - 3) < 0.05


def reason_text(r: dict) -> str:
    """The forecast's reason as a participant would describe it: what raises the risk, or (when the
    risk is low) what keeps it low."""
    return f"{r.get('text') or r['label']} ({'raises the risk' if r['direction'] == 'raises' else 'keeps the risk low'})"


def key_for(p: dict, today: date = STUDY_FIRST) -> dict:
    money = m.as_of(m.MoneyFacts(profile=p["profile"], transactions=p["transactions"], debts=p["debts"],
                                 checkins=p["checkins"]), today)
    profile, records, months = m.assess_inputs(money, today)
    a = assess(profile, records[:m.assessed_upto(months)])
    fc = a.get("forecast")
    dsr, dsr_edge = dsr_bucket(a["dsr"])
    cushion, cushion_edge = cushion_bucket(a["cushion_months"])
    return {
        "B1": BAND_WORDS[a["band"]], "B1_note": (f"this month's own band is {BAND_WORDS[a['raw_band_this_month']]}; "
                                                 "a better band shows only after it holds for 2 months (D-49)")
        if a["raw_band_this_month"] != a["band"] else "",
        "B2": dsr, "dsr": a["dsr"], "B2_edge": dsr_edge,
        "B3": "straight away",
        "B4": None if fc is None else (f"Out of 100 people like this, about {round(fc['probability'] * 100)} would get worse"
                                       + (" (already Red: run short of money; both wordings correct)"
                                          if fc.get("red_note") else "")),
        "B5": [reason_text(r) for r in (fc or {}).get("reasons", [])],
        "B6": "The future is uncertain, so it shows likely lows and highs",
        "B7": cushion, "cushion": a["cushion_months"], "B7_edge": cushion_edge,
        "B8": "meeting their own saving goal or keeping a cushion, month after month",
        "B9": [(x["short"], x["title"], x["text"]) for x in a["advice"][:2]],   # the short line shows first (D-108)
        "forecast_note": a.get("forecast_note"),
    }


def write(personas: list[dict]) -> str:
    text = render(personas)
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text, encoding="utf-8")
    return text


def render(personas: list[dict]) -> str:
    lines = ["# Comprehension answer keys (T-18; questionnaire Part B)", "",
             "Generated by `tools/personas/answer_key.py` from what the app shows each persona on its **start date, "
             "1 July 2026**. Every participant gets fresh copies of the personas, which start there (D-94), and "
             "answers Part B before using time travel (`docs/ethics/06_session_script.md`, D-95). "
             "Scoring: correct or incorrect against the key. "
             "**Draft for Patrick's review**, written before any participant takes part (the questions themselves "
             "were fixed in the ethics drafts).", "",
             "| | " + " | ".join(f"{p['meta']['name']}" for p in personas) + " |",
             "|---|" + "---|" * len(personas)]
    keys = [key_for(p) for p in personas]

    def row(label, cells):
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    row("**B1** band", [k["B1"] + (" ⚠" if k["B1_note"] else "") for k in keys])
    row("**B2** income to repayments", [f"{k['B2']} (shown {k['dsr']:.0%})" + (" ⚠" if k["B2_edge"] else "") for k in keys])
    row("**B3** a worse band shows", [k["B3"] for k in keys])
    row("**B4** the forecast means", [k["B4"] or "no forecast shown" for k in keys])
    row("**B5** main reason (free text)", [k["B5"][0] if k["B5"] else "-" for k in keys])
    row("**B6** why a range", [k["B6"] for k in keys])
    row("**B7** months of essentials covered", [f"{k['B7']} (shown {k['cushion']:.1f})" + (" ⚠" if k["B7_edge"] else "")
                                              for k in keys])
    row("**B8** the garden grows by", [k["B8"] for k in keys])
    row("**B9** suggested step (free text)", [k["B9"][0][0] if k["B9"] else "-" for k in keys])
    lines += ["", "## Accepting free-text answers (B5, B9)", ""]
    for p, k in zip(personas, keys):
        lines.append(f"**{p['meta']['name']}.** B5 correct if it names the first reason (the second is accepted too): "
                     + "; ".join(f"*{x}*" for x in k["B5"][:2]) + ". B9 correct if it describes the first step, "
                     "shown first as: " + " / ".join(f"*{s}* (behind Read more: {t}. {x})" for s, t, x in k["B9"][:1])
                     + ".")
        lines.append("")
    flagged = [(p["meta"]["name"], q, why) for p, k in zip(personas, keys)
               for q, why in (("B1", k["B1_note"]), ("B2", "the share is within 2 points of a bucket edge" if k["B2_edge"] else ""),
                              ("B7", "the months are within 0.05 of a bucket edge" if k["B7_edge"] else "")) if why]
    lines += ["## ⚠ Answers to look at before the pilot", ""]
    lines += [f"- **{n}, {q}:** {why}." for n, q, why in flagged] or ["- None."]
    lines += ["", "Options for a flagged answer: accept both neighbouring answers for that persona, make sure the "
              "screen shows the exact value (e.g. 59.2%), or choose another persona or start date (PS1)."]
    return "\n".join(lines) + "\n"


def main() -> None:
    personas = json.loads(OUT.read_text(encoding="utf-8"))["personas"]
    print(write(personas))


if __name__ == "__main__":
    main()
