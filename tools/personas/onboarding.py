"""The sign-up task (D-94): a card of made-up details that each participant types into the app's
onboarding, on an empty study account, and a check of what got saved.

    .venv\\Scripts\\python -m tools.personas.onboarding                    # -> docs/study/onboarding_card.md
    .venv\\Scripts\\python -m tools.personas.onboarding --participant P07  # after P07's task: what was saved

Why: the personas start with a finished sign-up, so without this task the study would never test
onboarding, the first thing every real user does. The card keeps rule 12 (synthetic data only):
participants never type anything about themselves.

What the check gives, for the report (secondary measures, not O4 criteria): the share of the card's
fields saved correctly, and the minutes from signing in to finishing sign-up (the profile's arrival
time minus the account's sign-in time). The researcher notes separately whether help was needed.
It reads the empty account's rows with the admin key (seed.Admin); run it before deleting the
participant's accounts.

The card's fields are the onboarding inputs in docs/app_plan.md §3 and the app's sign-up screens
(app/src/app/onboarding.tsx, D-124); keep both in step. app/src/lib/__tests__/onboarding.test.ts types
this card into the app's form and requires exactly EXPECTED_PROFILE and EXPECTED_DEBTS.
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path

from . import seed

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "study" / "onboarding_card.md"

# what the participant reads (made up; a situation none of the four personas has)
CARD = [
    ("Work", "You work full time for a company (an employee)."),
    ("Year of birth", "2002"),
    ("Take-home pay", "RM2,800 a month (after EPF and SOCSO)"),
    ("Usual monthly costs", "About RM1,900 a month (room rent, food, transport, phone and bills)"),
    ("Vehicle", "A motorcycle"),
    ("Living with parents", "No, you rent a room"),
    ("Money to family", "Yes, RM200 every month"),
    ("Festival you celebrate", "Hari Raya Aidilfitri"),
    ("Money you have now", "RM1,250 in your bank account and e-wallet. No other savings."),
    ("Debt 1", "PTPTN loan: RM14,500 left to pay, RM150 a month, which you pay yourself (not taken from your salary)"),
    ("Debt 2", "One Buy Now Pay Later plan: RM360 left to pay, RM120 a month"),
    ("Savings goal", "RM200 a month"),
    ("Avatar, skin tone, glasses", "Choose any you like"),
]

# what the database should hold afterwards: (table, field, expected value)
EXPECTED_PROFILE = {
    "employment_type": "employee", "birth_year": 2002, "declared_income": 2800, "typical_monthly_costs": 1900,
    "vehicle": "motorcycle", "lives_with_parents": False, "family_support": True,
    "festive_month": 3,                          # Hari Raya Aidilfitri falls in March in 2026 and 2027
    "onboarding_counted_money": 1250, "onboarding_other_money": 0, "savings_goal_monthly": 200,
}
EXPECTED_DEBTS = [                               # (kind, outstanding, monthly payment, deducted from salary)
    ("ptptn", 14500, 150, False),
    ("bnpl", 360, 120, False),
]


def render() -> str:
    lines = ["# Sign-up task card (made-up details)", "",
             "*Generated by `tools/personas/onboarding.py` (D-94). Shown to every participant on screen or on "
             "paper during the sign-up task. Everything on it is invented; please don't enter anything about "
             "yourself.*", "",
             "**Your task:** you have just installed FAST. Sign in with the account you were given, then set "
             "up the app using the details below.", "",
             "| | Details |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in CARD]
    lines += ["", "*For the researcher:* time the task from signing in to reaching the home screen (the check "
              "script also estimates it), and note whether the participant needed help.", ""]
    return "\n".join(lines)


def write() -> str:
    text = render()
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(text, encoding="utf-8")
    return text


def _same(a, b) -> bool:
    if isinstance(b, bool) or b is None or isinstance(b, str):
        return a == b
    try:
        return abs(float(a) - float(b)) < 0.005
    except (TypeError, ValueError):
        return False


def check(profile: dict | None, debts: list[dict], signed_in_at: str | None = None) -> dict:
    """Field by field: what the card says against what was saved. Debts match regardless of order."""
    rows = []
    for field, want in EXPECTED_PROFILE.items():
        got = None if profile is None else profile.get(field)
        rows.append((f"profile.{field}", want, got, _same(got, want)))
    left = list(debts)
    for kind, owed, monthly, deducted in EXPECTED_DEBTS:
        hit = next((d for d in left if d.get("kind") == kind), None)
        if hit:
            left.remove(hit)
        for field, want in (("outstanding", owed), ("monthly_payment", monthly), ("deducted_from_salary", deducted)):
            got = None if hit is None else hit.get(field)
            rows.append((f"debt {kind}.{field}", want, got, _same(got, want)))
    extra = len(left)
    minutes = None
    if profile and signed_in_at:
        minutes = round((datetime.fromisoformat(profile["created_at"]) - datetime.fromisoformat(signed_in_at))
                        .total_seconds() / 60, 1)
    correct = sum(ok for *_, ok in rows)
    return {"rows": rows, "correct": correct, "total": len(rows), "accuracy": correct / len(rows),
            "extra_debts": extra, "minutes": minutes, "finished": profile is not None}


def report(result: dict, code: str) -> str:
    lines = [f"Sign-up task, {code.upper()}: " + ("finished" if result["finished"] else "NOT finished (no profile)"),
             f"fields saved correctly: {result['correct']} / {result['total']} ({result['accuracy']:.0%})"
             + (f"; {result['extra_debts']} debt(s) not on the card" if result["extra_debts"] else ""),
             f"minutes from sign-in to finishing: {result['minutes'] if result['minutes'] is not None else 'unknown'}",
             ""] + [f"  {'ok ' if ok else 'X  '} {field}: card {want!r}, saved {got!r}" for field, want, got, ok in result["rows"]]
    return "\n".join(lines)


def main(argv=None, admin: seed.Admin | None = None) -> None:
    ap = argparse.ArgumentParser(description="The sign-up task card, or check what a participant saved")
    ap.add_argument("--participant", help="check this participant's empty account, e.g. P07")
    a = ap.parse_args(argv)
    if not a.participant:
        print(write())
        return
    code = seed.participant_code(a.participant)
    admin = admin or seed.Admin(seed.env("SUPABASE_URL"), seed.env("SUPABASE_SERVICE_ROLE_KEY"))
    user = next((u for u in admin.users() if u.get("email") == seed.onboarding_email(code)), None)
    if user is None:
        raise SystemExit(f"no sign-up account for {code.upper()} (made with seed --participant {code.upper()}?)")
    profiles = admin.select("profiles", user["id"])
    result = check(profiles[0] if profiles else None, admin.select("debts", user["id"]), user.get("last_sign_in_at"))
    print(report(result, code))
    print(json.dumps({k: v for k, v in result.items() if k != "rows"}))     # one line to paste into the sheet


if __name__ == "__main__":
    main()
