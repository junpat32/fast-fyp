"""The expert review form (D-101): a finance lecturer or debt counsellor rates the personas' realism,
the band rules and every advice text, in about 25 minutes. Generated from the app's own texts and the
personas, so it always shows the current wording (regenerate after any wording change, W2).

    .venv\\Scripts\\python -m tools.personas.expert_form      # -> docs/study/expert_review_form.md

Why: real-world validity and the advice's usefulness can't be measured on synthetic data (D-99 scores
3/10 and 5/10); an expert's structured ratings are the evidence an FYP can collect without real
financial data (rule 12). The ratings are summarised as medians in the report.
"""
from __future__ import annotations

import json

from engine.bands import load_thresholds
from engine.rules import _ADVICE, limits

from .answer_key import key_for
from .build import OUT, ROOT

DOC = ROOT / "docs" / "study" / "expert_review_form.md"
SAMPLE = {"shortfalls": 1, "debt_payments": "RM400", "dsr_pct": "57%", "cushion_months": "0.5", "gap_to_first": "RM600",
          "gap_to_next": "RM3,000", "bnpl_plans": 2, "bnpl_monthly": "RM150", "risk_pct": "34%", "overspend_pct": "10%",
          "new_band": "Green"}
SCALE = "☐1 ☐2 ☐3 ☐4 ☐5"


def advice_rows() -> list[tuple[str, str]]:
    fixed = {**limits(load_thresholds()), **SAMPLE}
    rows = []
    for rule, texts in _ADVICE.items():
        for key, text in texts.items():
            if key.startswith("text"):
                when = "" if key == "text" else f" ({key[5:].replace('_', ' ')})"
                short = texts.get(key.replace("text", "short", 1), texts["short"]).format(**fixed)
                rows.append((f"{rule.split('_')[0]}{when}: {texts['title'].format(**fixed)}",
                             f"*Shown first:* {short} *Read more:* {text.format(**fixed)}"))
    return rows


def render(personas: list[dict]) -> str:
    t = load_thresholds()
    d = t["dsr"]
    L = ["# FAST: expert review form", "",
         "*Generated by `tools/personas/expert_form.py` (D-101) from the app's current texts. For Patrick: send it "
         "with a short note; check with your supervisor whether MMU's ethics approval should mention this review.*", "",
         "Thank you for helping. FAST is a final-year-project prototype (Multimedia University) that explains money "
         "risk to Malaysians aged 18–35: a debt band, a 3-month forecast with reasons, and plain-language advice. "
         "Everything below uses **made-up people and numbers**. It takes about **25 minutes**. Scales: 1 = strongly "
         "disagree / very poor, 5 = strongly agree / very good. Skip anything you prefer not to answer.", "",
         "**About you** (nothing that identifies you is recorded):", "",
         "- Role: ☐ debt or credit counsellor ☐ finance or economics lecturer ☐ banking or lending ☐ other: ____",
         "- Years of experience: ☐ under 3 ☐ 3–10 ☐ over 10",
         "- ☐ I agree that my comments may be quoted **anonymously** in the FYP report.", "",
         "## Part A: the made-up people (personas)", "",
         "How realistic is each person for a young Malaysian today?", ""]
    for i, p in enumerate(personas, 1):
        k = key_for(p)
        prof = p["profile"]
        listed = [x["label"] for x in p["debts"]]
        if any(tx.get("is_bnpl") for tx in p["transactions"]):          # BNPL is counted from purchases, not listed
            listed.append("Buy Now Pay Later plans")
        debts = ", ".join(listed) or "none"
        L += [f"**A{i}. {p['meta']['name']}.** {p['meta']['story']} Work: {prof['employment_type']}; take-home "
              f"about RM{prof['declared_income']:,.0f} a month; debts: {debts}. What the app shows: band "
              f"**{k['B1']}**, debt payments {k['dsr']:.0%} of income, cash covers {k['cushion']:.1f} months of costs.", "",
              f"Realistic: {SCALE}   Comment: ________", ""]
    L += ["## Part B: the debt band", "",
          f"The band uses the **debt service ratio** (monthly debt payments ÷ net monthly income): Green below "
          f"{d['green_below']:.0%}, Yellow {d['green_below']:.0%} to below {d['red_at_or_above']:.0%}, Red "
          f"{d['red_at_or_above']:.0%} or more (Bank Negara treats above 60% as vulnerable). Once Red, it stays Red until "
          f"the ratio is below {d['leave_red_below']:.0%}; a better band shows only after "
          f"{t['improvement_confirm_months']} months in a row; no band is shown when typical income is below "
          f"RM{t['insufficient_income_below_rm']}.", "",
          f"- B1. These thresholds are reasonable for young Malaysian borrowers: {SCALE}",
          f"- B2. The debt service ratio is the right headline measure for this age group: {SCALE}",
          f"- B3. Waiting {t['improvement_confirm_months']} months before showing a better band is sensible: {SCALE}",
          "- Comment: ________", "",
          "## Part C: the advice texts", "",
          "Amounts and percentages are examples. For each text: **Accurate** (correct and not misleading), **Safe** (no "
          "harmful suggestion and no product recommendation: yes / no), **Suitable** for 18–35-year-old Malaysians, "
          "**Clear**. Suggest better wording if you like.", "",
          "| # | Advice | Accurate | Safe | Suitable | Clear | Better wording |", "|---|---|---|---|---|---|---|"]
    for i, (title, text) in enumerate(advice_rows(), 1):
        L.append(f"| C{i} | **{title}**. {text} | /5 | Y / N | /5 | /5 | |")
    L += ["", "## Part D: the forecast and its reasons", "",
          "Example as a user sees it: *\"About 68 out of 100 people like you get into money trouble (a worse band or "
          "running short) in the next 3 months. What raises your risk: You ran short of money recently; Your cash "
          "cushion is smaller than average; Your typical monthly income is lower than average.\"* For someone already "
          "in Red, a line adds: *\"You're already in Red, so this is the chance of running short of money.\"*", "",
          f"- D1. A young adult would understand what this means: {SCALE}",
          f"- D2. Showing a chance (\"out of 100 people\") rather than a yes/no warning is the right choice: {SCALE}",
          f"- D3. The reasons are things a person could act on: {SCALE}",
          "- Comment: ________", "",
          "## Part E: overall", "",
          f"- E1. I would suggest an app like this to a client or student aged 18–35: {SCALE}",
          "- E2. The biggest risk or weakness I see: ________",
          "- E3. Advice that is missing (for example about total debt, falling savings, or unexpected costs): ________", "",
          "Thank you. Please return the form to the researcher; your answers are used only for the FYP report."]
    return "\n".join(L) + "\n"


def write(personas: list[dict]) -> str:
    text = render(personas)
    DOC.write_text(text, encoding="utf-8")
    return text


def main() -> None:
    print(write(json.loads(OUT.read_text(encoding="utf-8"))["personas"]))


if __name__ == "__main__":
    main()
